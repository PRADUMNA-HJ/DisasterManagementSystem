package com.disastermanagement.enums;

/**
 * Enumeration defining categories of disaster relief resources requested by users/shelters.
 */
public enum ResourceType {
    /**
     * Food rations, meal kits, and nutritional supplies.
     */
    FOOD,

    /**
     * Clean drinking water and hydration packs.
     */
    WATER,

    /**
     * First aid kits, prescription drugs, and medical equipment.
     */
    MEDICINE,

    /**
     * Blankets, protective gear, and wearable clothing.
     */
    CLOTHES
}
